    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        // TODO add your handling code here:
        if (indice < 5) {
        String nombre = txtNombres.getText().trim();
        
        if (nombre.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor, ingrese un nombre.", "Campo vacío", JOptionPane.WARNING_MESSAGE);
            return;
        }

        asistentes[indice] = nombre;
        indice++;

        txtNombres.setText("");
        txtNombres.requestFocus();

        JOptionPane.showMessageDialog(this, "Asistente " + indice + " de 5 registrado correctamente: " + nombre);

        if (indice == 5) {
            JOptionPane.showMessageDialog(this, "Se han registrado los 5 asistentes. Ya puede presionar 'Exportar lista'.");
        }
    } else {
        JOptionPane.showMessageDialog(this, "Ya se han ingresado los 5 asistentes requeridos.", "Límite alcanzado", JOptionPane.WARNING_MESSAGE);
    }
    }//GEN-LAST:event_btnRegistrarActionPerformed

