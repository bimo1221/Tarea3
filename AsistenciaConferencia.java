    private void btnExportarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExportarActionPerformed
        // TODO add your handling code here:
        if (indice < 5) {
        JOptionPane.showMessageDialog(this, "Debe registrar los 5 asistentes antes de exportar la lista. Registrados: " + indice, "Incompleto", JOptionPane.WARNING_MESSAGE);
        return;
    }

    File carpetaTemp = new File("temp");
    if (!carpetaTemp.exists()) {
        carpetaTemp.mkdir();
    }

    File archivoReporte = new File(carpetaTemp, "sunombre_asistencia.txt");
    try (PrintWriter writer = new PrintWriter(new FileWriter(archivoReporte))) {
        writer.println("Lista de Asistencia");

        for (int i = 0; i < asistentes.length; i++) {
            writer.println((i + 1) + ". " + asistentes[i]);
        }

        JOptionPane.showMessageDialog(this, "Lista exportada con éxito en:\n" + archivoReporte.getAbsolutePath(), "Éxito", JOptionPane.INFORMATION_MESSAGE);

    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, "Error al guardar el archivo: " + e.getMessage(), "Error E/S", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnExportarActionPerformed

