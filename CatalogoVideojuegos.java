    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        // TODO add your handling code here:
        try {
        String titulo = txtTitulo.getText().trim();
        String consola = txtConsola.getText().trim();
        String anioTexto = txtAnio.getText().trim();

        if (titulo.isEmpty() || consola.isEmpty() || anioTexto.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Debe completar todos los campos del videojuego.", "Campos vacíos", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int anio = Integer.parseInt(anioTexto);

        Videojuego juego = new Videojuego(titulo, consola, anio);

        catalogo.add(juego);

        JOptionPane.showMessageDialog(this, "Juego '" + titulo + "' agregado exitosamente al catálogo.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
        txtTitulo.setText("");
        txtConsola.setText("");
        txtAnio.setText("");
        txtTitulo.requestFocus();

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "El año de lanzamiento debe ser un número entero válido.", "Error de entrada", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnMostrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMostrarActionPerformed
        // TODO add your handling code here:
        txtAreaCatalogo.setText("");

    if (catalogo.isEmpty()) {
        txtAreaCatalogo.setText("El catálogo se encuentra vacío.");
        return;
    }

    StringBuilder reporte = new StringBuilder();
    reporte.append("=== CATÁLOGO DE VIDEOJUEGOS ===\n\n");

    for (int i = 0; i < catalogo.size(); i++) {
        Videojuego v = catalogo.get(i);
        reporte.append((i + 1)).append(". Título: ").append(v.titulo).append("\n");
        reporte.append("   Consola: ").append(v.consola).append("\n");
        reporte.append("   Año: ").append(v.anioLanzamiento).append("\n");
        reporte.append("-----------------------------------\n");
    }

    reporte.append("\nCantidad total de juegos registrados: ").append(catalogo.size());

    txtAreaCatalogo.setText(reporte.toString());
    }//GEN-LAST:event_btnMostrarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        if (catalogo.size() > 0) {
        int ultimoIndice = catalogo.size() - 1;
        
        String tituloEliminado = catalogo.get(ultimoIndice).titulo;

        catalogo.remove(ultimoIndice);

        JOptionPane.showMessageDialog(this, 
            "El juego '" + tituloEliminado + "' fue eliminado del catálogo.", 
            "Elemento eliminado", JOptionPane.INFORMATION_MESSAGE);

    } else {
        JOptionPane.showMessageDialog(this, 
            "No hay elementos en el catálogo para eliminar.", 
            "Lista vacía", JOptionPane.WARNING_MESSAGE);
    }
    }//GEN-LAST:event_btnEliminarActionPerformed

