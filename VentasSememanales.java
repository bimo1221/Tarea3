    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        // TODO add your handling code here:
        if (indice < 5){
            try {
                double monto = Double.parseDouble(txtMonto.getText().trim());
                if (monto < 0){
                    JOptionPane.showMessageDialog(this,"Por favor, ingresa un monto positivo,", "Error de monto",JOptionPane.ERROR_MESSAGE);
                    return;
                }
                ventas[indice] = monto;
                indice++;
            JOptionPane.showMessageDialog(this, "Venta " + indice + " de 5 ingresada con éxito.");
            txtMonto.setText("");
            txtMonto.requestFocus();
            if (indice == 5){
                JOptionPane.showMessageDialog(this, "Has completado los 5 montos. Presiona 'Generar reporte'.");
            }
            }catch(NumberFormatException e ){
                JOptionPane.showMessageDialog(this, "Por favor, ingrese un número válido.", "Error de entrada", JOptionPane.ERROR_MESSAGE);
            }
        }else{
            JOptionPane.showMessageDialog(this, "Ya ha ingresado los 5 montos requeridos.", "Límite alcanzado", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnGenerarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerarActionPerformed
        // TODO add your handling code here:
        if (indice < 5){
         JOptionPane.showMessageDialog(this, "Debe ingresar las 5 ventas antes de generar el reporte. Ventas actuales: " + indice, "Incompleto", JOptionPane.WARNING_MESSAGE);
        return;
        }
        double totalVendido = 0;
        int ventasSuperiores500 = 0;
        for (int i = 0;i < ventas.length;i++){
            totalVendido += ventas[i];
            if(ventas[i] > 500.00){
                ventasSuperiores500++;
            }
        }
        File carpetaTemp = new File ("temp");
        if (!carpetaTemp.exists()){
            carpetaTemp.mkdir();
        }
        File archivoReporte = new File(carpetaTemp, "sunombre_reporte_ventas.txt");
        try (PrintWriter writer = new PrintWriter(new FileWriter(archivoReporte))){
        writer.println("Reporte de Ventas");
        writer.printf("Total Vendido: %.2f%n", totalVendido);
        writer.println("Ventas superiores a Q500: " + ventasSuperiores500);
        JOptionPane.showMessageDialog(this, "Reporte generado exitosamente en:\n" + archivoReporte.getAbsolutePath(), "Éxito", JOptionPane.INFORMATION_MESSAGE);
        }catch(IOException e ){
            JOptionPane.showMessageDialog(this, "Error al escribir el archivo: " + e.getMessage(), "Error E/S", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnGenerarActionPerformed

