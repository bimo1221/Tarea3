    private void btnCargarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCargarActionPerformed
        // TODO add your handling code here:
        File archivo = new File(rutaArchivo);
        if (!archivo.exists()) {
        JOptionPane.showMessageDialog(this, 
            "El archivo no existe en la ruta: " + archivo.getAbsolutePath() + 
            "\nAsegúrese de crear la carpeta 'temp' y el archivo 'temperaturas.txt'.", 
            "Archivo no encontrado", JOptionPane.ERROR_MESSAGE);
        return;
    }
        try (BufferedReader br = new BufferedReader(new FileReader(archivo))) {
        String linea;
        indice = 0;
        while ((linea = br.readLine()) != null && indice < 6) {
            linea = linea.trim();
            if (!linea.isEmpty()) {
                temperaturas[indice] = Double.parseDouble(linea);
                indice++;
            }
        }
        if (indice == 6) {
            JOptionPane.showMessageDialog(this, 
                "Datos cargados exitosamente en memoria (6 registros).", 
                "Lectura exitosa", JOptionPane.INFORMATION_MESSAGE);
        } else {
            JOptionPane.showMessageDialog(this, 
                "Se cargaron " + indice + " registros de temperatura de los 6 esperados.", 
                "Lectura parcial", JOptionPane.WARNING_MESSAGE);
        }

    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, 
            "Error al leer el archivo: " + e.getMessage(), 
            "Error de Lectura", JOptionPane.ERROR_MESSAGE);
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, 
            "El archivo contiene datos que no son números válidos.", 
            "Error de Formato", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnCargarActionPerformed

    private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularActionPerformed
        // TODO add your handling code here:
        if (indice < 6) {
        JOptionPane.showMessageDialog(this, 
            "Debe cargar los 6 datos del archivo antes de calcular las estadísticas.", 
            "Datos insuficientes", JOptionPane.WARNING_MESSAGE);
        return;
    }

    double suma = 0;
    int diasCalidos = 0;
    int diasFrescos = 0;

    for (int i = 0; i < temperaturas.length; i++) {
        suma += temperaturas[i];

        if (temperaturas[i] >= 25.0) {
            diasCalidos++; 
        } else {
            diasFrescos++; 
        }
    }
    double promedio = suma / temperaturas.length;
    jTextArea1.setText("");

    StringBuilder reporte = new StringBuilder();
    reporte.append("Análisis Climático\n");
    reporte.append("---------------\n");
    reporte.append(String.format("Promedio de Temperatura: %.1f%n", promedio));
    reporte.append("Días Cálidos (>= 25º): ").append(diasCalidos).append("\n");
    reporte.append("Días Frescos (< 25º): ").append(diasFrescos);
    jTextArea1.setText(reporte.toString());
    }//GEN-LAST:event_btnCalcularActionPerformed

