    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        String busqueda = txtBuscar.getText().trim();
        if (busqueda.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Ingrese el nombre de un álbum para buscar.", "Campo vacío", JOptionPane.WARNING_MESSAGE);
        return;
    }

    boolean encontrado = false;
    for (int i = 0; i < titulos.length; i++) {
        if (titulos[i] != null && titulos[i].equalsIgnoreCase(busqueda)) {
            lblAnoActual.setText("Año actual: " + anios[i]);
            encontrado = true;
            JOptionPane.showMessageDialog(this, "Álbum encontrado: " + titulos[i] + " (" + anios[i] + ")", "Éxito", JOptionPane.INFORMATION_MESSAGE);
            break;
        }
    }

    if (!encontrado) {
        lblAnoActual.setText("Año actual: -");
        JOptionPane.showMessageDialog(this, "No se encontró el álbum buscado.", "Sin resultados", JOptionPane.WARNING_MESSAGE);
    }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
        String albumBuscado = txtBuscar.getText().trim();
    String nuevoAnoTexto = txtNuevoAno.getText().trim();

    if (albumBuscado.isEmpty() || nuevoAnoTexto.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Debe ingresar el álbum a buscar y el nuevo año.", "Datos incompletos", JOptionPane.WARNING_MESSAGE);
        return;
    }

    try {
        int nuevoAno = Integer.parseInt(nuevoAnoTexto);
        boolean encontrado = false;

        for (int i = 0; i < titulos.length; i++) {
            if (titulos[i] != null && titulos[i].equalsIgnoreCase(albumBuscado)) {
                anios[i] = nuevoAno;
                encontrado = true;
                break;
            }
        }

        if (!encontrado) {
            JOptionPane.showMessageDialog(this, "No se puede actualizar. El álbum no existe en los registros.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try (PrintWriter writer = new PrintWriter(new FileWriter(rutaArchivo, false))) {
            for (int i = 0; i < titulos.length; i++) {
                if (titulos[i] != null) {
                    writer.println(titulos[i] + "," + anios[i]);
                }
            }
            
            lblAnoActual.setText("Año actual: " + nuevoAno);
            
            JOptionPane.showMessageDialog(this, "Registro actualizado y archivo discos.csv guardado con éxito.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
            txtNuevoAno.setText("");

        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Error al guardar en el archivo: " + e.getMessage(), "Error E/S", JOptionPane.ERROR_MESSAGE);
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "El nuevo año debe ser un número entero válido.", "Error de entrada", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnActualizarActionPerformed

