    private void cargarDatosAutomaticos(){
        File archivo = new File(rutaArchivo);
        if (!archivo.exists()) {
            JOptionPane.showMessageDialog(this, 
                "No se encontró el archivo en la ruta: " + archivo.getAbsolutePath(), 
                "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try (Scanner sc = new Scanner(archivo)) {
            int i = 0;
            while (sc.hasNextLine() && i < 5) {
                String linea = sc.nextLine().trim();
                if (!linea.isEmpty()) {
                    String[] partes = linea.split(",");
                    if (partes.length == 2) {
                        titulos[i] = partes[0].trim();
                        anios[i] = Integer.parseInt(partes[1].trim());
                        i++;
                    }
                }
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, 
                "Error al cargar datos automáticos: " + e.getMessage(), 
                "Error de lectura", JOptionPane.ERROR_MESSAGE);
        }
    }
