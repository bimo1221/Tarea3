    private void btnCrearArtistaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearArtistaActionPerformed
        // TODO add your handling code here:
        try {
        String nombre = txtNombreArtista.getText().trim();
        String pais = txtPaisOrigen.getText().trim();
        String oyentesTexto = txtOyentes.getText().trim();

        if (nombre.isEmpty() || pais.isEmpty() || oyentesTexto.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Complete todos los campos del artista.", "Campos vacíos", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int oyentes = Integer.parseInt(oyentesTexto);
        Artistas a = new Artistas();
        a.nombre = nombre;
        a.paisOrigen = pais;
        a.oyentesMensuales = oyentes;

        // 3. Imprimir el estado del objeto en el JTextArea con .append()
        txtAreaReporte.append("=== ARTISTA REGISTRADO ===\n");
        txtAreaReporte.append("Nombre: " + a.nombre + "\n");
        txtAreaReporte.append("País de Origen: " + a.paisOrigen + "\n");
        txtAreaReporte.append("Oyentes Mensuales: " + a.oyentesMensuales + "\n");
        txtAreaReporte.append("-----------------------------------\n\n");
        txtNombreArtista.setText("");
        txtPaisOrigen.setText("");
        txtOyentes.setText("");

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Los oyentes mensuales deben ser un número entero válido.", "Error de entrada", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnCrearArtistaActionPerformed

    private void btnCrearCancionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearCancionActionPerformed
        // TODO add your handling code here:
        try {
        String titulo = txtTituloCancion.getText().trim();
        String duracionTexto = txtDuracion.getText().trim();
        String genero = txtGenero.getText().trim();
        String artista = txtArtistaCancion.getText().trim();

        if (titulo.isEmpty() || duracionTexto.isEmpty() || genero.isEmpty() || artista.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Complete todos los campos de la canción.", "Campos vacíos", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int duracion = Integer.parseInt(duracionTexto);
        Cancion c = new Cancion();
        c.titulo = titulo;
        c.duracionSegundos = duracion;
        c.genero = genero;
        c.nombreArtista = artista;
        txtAreaReporte.append("=== CANCIÓN REGISTRADA ===\n");
        txtAreaReporte.append("Título: " + c.titulo + "\n");
        txtAreaReporte.append("Duración: " + c.duracionSegundos + " segundos\n");
        txtAreaReporte.append("Género: " + c.genero + "\n");
        txtAreaReporte.append("Artista: " + c.nombreArtista + "\n");
        txtAreaReporte.append("-----------------------------------\n\n");
        txtTituloCancion.setText("");
        txtDuracion.setText("");
        txtGenero.setText("");
        txtArtistaCancion.setText("");

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "La duración en segundos debe ser un número entero válido.", "Error de entrada", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnCrearCancionActionPerformed

